import { link, mkdir, readFile, realpath, rename, rm, symlink, utimes, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import {
  inspectModelRouting,
  splitPatchEntries,
  syncModelRoutingFromDesktop,
} from '../../../src/agent/dsh/profile-sync.js';

// f0.5++: DSH refuses to run the `desktop` profile from a CLI, so Feishu runs
// its own profile and mirrors the desktop's model routing into it. These tests
// pin the mirror: only the two routing entries travel, the desktop file is
// never written, and a broken source leaves the last good routing alone.

const DESKTOP_PATCH = [
  '# your patch layer',
  '- id: agent-default-model',
  '  name: "@deepseek-ai/dsh-agent-default-model"',
  '  config:',
  '    provider: aidu',
  '    model: Qwen4-Max',
  '    reasoningEffort: max',
  '- id: ui-settings',
  '  name: "@deepseek-ai/dsh-client-ui-settings"',
  '  config:',
  '    enabled: false',
  '- id: llm-pi-ai',
  '  name: "@deepseek-ai/dsh-llm-pi-ai"',
  '  config:',
  '    providers:',
  '      aidu:',
  '        apiKeyEnv: AIDU_API_KEY',
  '        models:',
  '          - id: Qwen4-Max',
  '          - id: GLM-5.3-Flash',
  '      gpt:',
  '        apiKeyEnv: GPT_API_KEY',
  '        models:',
  '          - id: gpt-6-astra',
  '',
].join('\n');

const GENERATED = [
  '# GENERATED by aiduCAT — do not edit by hand.',
  '# Mirrored from the desktop profile so Feishu follows the GUI model settings.',
  '# Source: $DSH_HOME/profiles/desktop/cordis.patch.yml',
  '# Regenerated automatically whenever that file changes.',
  '',
  '',
].join('\n');
const GENERATED_PATCH = GENERATED + DESKTOP_PATCH.slice(DESKTOP_PATCH.indexOf('- id: agent-default-model'))
  .replace(/- id: ui-settings\n[\s\S]*?(?=- id: llm-pi-ai)/, '');
const OLD_PATCH = GENERATED_PATCH.replace('Qwen4-Max', 'Old-Model').replace('id: Qwen4-Max', 'id: Old-Model');

const cleanups: Array<() => Promise<void>> = [];
const originalHome = process.env.DSH_HOME;
const originalProfile = process.env.AIDUCAT_DSH_PROFILE;

afterEach(async () => {
  if (originalHome === undefined) delete process.env.DSH_HOME;
  else process.env.DSH_HOME = originalHome;
  if (originalProfile === undefined) delete process.env.AIDUCAT_DSH_PROFILE;
  else process.env.AIDUCAT_DSH_PROFILE = originalProfile;
  await Promise.all(cleanups.splice(0).map((c) => c()));
});

async function home(desktopPatch: string | null, targetPatch: string | null = OLD_PATCH) {
  const { mkdtemp } = await import('node:fs/promises');
  const dir = await mkdtemp(join(await realpath(tmpdir()), 'dsh-sync-'));
  cleanups.push(() => rm(dir, { recursive: true, force: true }));
  await mkdir(join(dir, 'profiles', 'desktop'), { recursive: true });
  await mkdir(join(dir, 'profiles', 'headless'), { recursive: true });
  if (desktopPatch !== null) {
    await writeFile(join(dir, 'profiles', 'desktop', 'cordis.patch.yml'), desktopPatch, 'utf8');
  }
  if (targetPatch !== null) {
    await writeFile(join(dir, 'profiles', 'headless', 'cordis.patch.yml'), targetPatch, 'utf8');
  }
  process.env.DSH_HOME = dir;
  delete process.env.AIDUCAT_DSH_PROFILE;
  return {
    dir,
    desktop: join(dir, 'profiles', 'desktop', 'cordis.patch.yml'),
    headless: join(dir, 'profiles', 'headless', 'cordis.patch.yml'),
  };
}

describe('splitPatchEntries', () => {
  it('keeps each top-level entry byte-faithful and ignores comments', () => {
    const entries = splitPatchEntries(DESKTOP_PATCH);
    expect([...entries.keys()]).toEqual(['agent-default-model', 'ui-settings', 'llm-pi-ai']);
    expect(entries.get('agent-default-model')).toContain('model: Qwen4-Max');
    expect(entries.get('agent-default-model')).not.toContain('ui-settings');
  });
});

describe('syncModelRoutingFromDesktop', () => {
  it('mirrors exactly the two routing entries into the run profile', async () => {
    const h = await home(DESKTOP_PATCH);
    const result = syncModelRoutingFromDesktop();
    expect(result.status).toBe('written');

    const mirrored = await readFile(h.headless, 'utf8');
    expect(mirrored).toContain('GENERATED by aiduCAT');
    expect(mirrored).toContain('model: Qwen4-Max');
    expect(mirrored).toContain('GLM-5.3-Flash');
    expect(mirrored).toContain('apiKeyEnv: AIDU_API_KEY');
    // UI-client entries never travel: they configure the GUI, not a run.
    expect(mirrored).not.toContain('ui-settings');
    // Supported provider routing is mirrored, including only credential names.
    expect(mirrored).toContain('apiKeyEnv: GPT_API_KEY');
    expect(mirrored).not.toMatch(/sk-[A-Za-z0-9]/);
  });

  it('never writes the desktop profile', async () => {
    const h = await home(DESKTOP_PATCH);
    const before = await readFile(h.desktop, 'utf8');
    syncModelRoutingFromDesktop();
    expect(await readFile(h.desktop, 'utf8')).toBe(before);
  });

  it('mirrors the routing rows even when the desktop carries directive blocks', async () => {
    // Real incident 2026-11-18: an aiduMEI MCP `insert:` block was added to the
    // desktop profile after the routing entries. The mirror must skip the whole
    // directive block — including the indented `- id:` rows inside it — instead
    // of declaring the whole document invalid and freezing the model list.
    const withMcp = [
      ...DESKTOP_PATCH.split('\n').filter((l) => l.trim() !== ''),
      '',
      '# === aiduMEI long-term memory MCP (added outside aiduCAT) ===',
      '- insert:',
      '    - id: mcp-aidumei',
      "        name: '@deepseek-ai/dsh-mcp-client'",
      '        command: C:\\\\tools\\\\python.exe',
      '        args:',
      '            - mcp-stdio.py',
      '',
    ].join('\n');
    const h = await home(withMcp);
    const result = syncModelRoutingFromDesktop();
    expect(result.status).toBe('written');
    const mirrored = await readFile(h.headless, 'utf8');
    expect(mirrored).toContain('model: Qwen4-Max');
    // Neither the directive block nor anything from it may leak into the mirror.
    expect(mirrored).not.toContain('insert');
    expect(mirrored).not.toContain('mcp-aidumei');
    expect(mirrored).not.toContain('dsh-mcp-client');
    expect(mirrored).not.toContain('python.exe');
  });

  it('reports unchanged when nothing moved, and re-syncs after an edit', async () => {
    const h = await home(DESKTOP_PATCH);
    expect(syncModelRoutingFromDesktop().status).toBe('written');
    expect(syncModelRoutingFromDesktop().status).toBe('unchanged');

    // The desktop GUI rewrites its patch when the owner adds a model.
    await writeFile(h.desktop, DESKTOP_PATCH.replace('      - id: GLM-5.3-Flash', '      - id: GLM-5.3-Flash\n          - id: Qwen3.8-Flash'), 'utf8');
    await utimes(h.desktop, new Date(), new Date(Date.now() + 5_000));
    expect(syncModelRoutingFromDesktop().status).toBe('written');
    expect(await readFile(h.headless, 'utf8')).toContain('Qwen3.8-Flash');
  });

  it('leaves the previous routing alone when the source has no model row', async () => {
    const h = await home(DESKTOP_PATCH);
    syncModelRoutingFromDesktop();
    const good = await readFile(h.headless, 'utf8');

    // A torn write: provider present, model gone.
    await writeFile(h.desktop, '- id: agent-default-model\n  config:\n    provider: aidu\n', 'utf8');
    const result = syncModelRoutingFromDesktop();
    expect(result.status).toBe('source-invalid');
    expect(await readFile(h.headless, 'utf8')).toBe(good);
  });

  it('does nothing when the desktop profile is absent', async () => {
    const h = await home(null);
    expect(syncModelRoutingFromDesktop().status).toBe('source-missing');
    expect(inspectModelRouting().status).toBe('source-missing');
    expect(await readFile(h.headless, 'utf8')).toBe(OLD_PATCH);
  });

  it('does not create a missing headless patch or custom profile directory', async () => {
    const h = await home(DESKTOP_PATCH, null);
    expect(syncModelRoutingFromDesktop().status).toBe('target-missing');
    await expect(readFile(h.headless, 'utf8')).rejects.toHaveProperty('code', 'ENOENT');
    expect(inspectModelRouting('aiducat-run').status).toBe('target-missing');
    expect(syncModelRoutingFromDesktop('aiducat-run').status).toBe('target-missing');
    await expect(mkdir(join(h.dir, 'profiles', 'aiducat-run'))).resolves.toBeUndefined();
  });

  it('honours an existing generated custom profile and an explicit profile override', async () => {
    const h = await home(DESKTOP_PATCH);
    process.env.AIDUCAT_DSH_PROFILE = 'aiducat-run';
    const dir = join(h.dir, 'profiles', 'aiducat-run');
    const custom = join(dir, 'cordis.patch.yml');
    await mkdir(dir);
    await writeFile(custom, OLD_PATCH);
    expect(inspectModelRouting()).toMatchObject({ status: 'stale', target: custom });
    expect(inspectModelRouting('headless')).toMatchObject({ status: 'stale', target: h.headless });
    expect(syncModelRoutingFromDesktop().status).toBe('written');
    expect(await readFile(custom, 'utf8')).toContain('model: Qwen4-Max');
    expect(await readFile(h.headless, 'utf8')).toBe(OLD_PATCH);
    expect(syncModelRoutingFromDesktop('headless').status).toBe('written');
  });

  it.each([
    'desktop', 'DeSkToP', 'desktop.', ' desktop  ', '.', '..', 'x/../headless',
    '../headless', '..\\headless', 'desktop::$DATA', 'C:\\headless', '/headless', 'NUL',
  ])('rejects an unsafe profile name %j for both inspection and sync', async (profile) => {
    const h = await home(DESKTOP_PATCH);
    process.env.AIDUCAT_DSH_PROFILE = profile;
    expect(inspectModelRouting()).toMatchObject({ status: 'target-unsafe', inSync: false });
    expect(syncModelRoutingFromDesktop()).toEqual({ status: 'target-unsafe' });
    expect(await readFile(h.desktop, 'utf8')).toBe(DESKTOP_PATCH);
    expect(await readFile(h.headless, 'utf8')).toBe(OLD_PATCH);
  });

  it.each([
    DESKTOP_PATCH,
    GENERATED.split('\n')[0] + '\n' + DESKTOP_PATCH,
    GENERATED + DESKTOP_PATCH,
    GENERATED_PATCH + '- config: {}\n',
    GENERATED_PATCH + '# user-maintained comment\n',
  ])('does not overwrite unmanaged/customized patches (%#)', async (patch) => {
    const h = await home(DESKTOP_PATCH, patch);
    expect(inspectModelRouting()).toMatchObject({ status: 'target-unmanaged', inSync: false });
    expect(syncModelRoutingFromDesktop().status).toBe('target-unmanaged');
    expect(await readFile(h.headless, 'utf8')).toBe(patch);
  });

  const SECRET = 'test-raw-credential-not-for-the-mirror';
  it.each([
    DESKTOP_PATCH.replace('apiKeyEnv: AIDU_API_KEY', `apiKey: ${SECRET}`),
    DESKTOP_PATCH.replace('apiKeyEnv: AIDU_API_KEY', `headers:\n          Authorization: Bearer ${SECRET}`),
    DESKTOP_PATCH.replace('        models:', `        baseURL: https://example.invalid/v1?token=${SECRET}\n        models:`),
    DESKTOP_PATCH.replace('        models:', `        baseURL: https://user:${SECRET}@example.invalid/v1\n        models:`),
    DESKTOP_PATCH.replace('provider: aidu', 'provider: *provider'),
    DESKTOP_PATCH.replace('model: Qwen4-Max', 'model: null'),
    DESKTOP_PATCH.replace('model: Qwen4-Max', 'model: Missing-Model'),
    DESKTOP_PATCH + '---\n',
    DESKTOP_PATCH + DESKTOP_PATCH,
    DESKTOP_PATCH.slice(0, -1),
    DESKTOP_PATCH.split('- id: llm-pi-ai')[0]!,
  ])('rejects unsupported, torn, or secret-bearing source content (%#)', async (patch) => {
    const h = await home(patch);
    expect(inspectModelRouting()).toMatchObject({ status: 'source-invalid', sourceValid: false, inSync: false });
    const result = syncModelRoutingFromDesktop();
    expect(result.status).toBe('source-invalid');
    expect(JSON.stringify(result)).not.toContain(SECRET);
    expect(await readFile(h.headless, 'utf8')).toBe(OLD_PATCH);
  });

  it('supports desktop block model metadata and CRLF line endings', async () => {
    const source = DESKTOP_PATCH.replace('- id: Qwen4-Max', [
      '- id: Qwen4-Max', '            contextWindow: 256000', '            input:',
      '              - text', '            reasoningEfforts:', '              off: null', '              high: high',
    ].join('\n')).replace(/\n/g, '\r\n');
    const h = await home(source, OLD_PATCH.replace(/\n/g, '\r\n'));
    expect(inspectModelRouting()).toMatchObject({ status: 'stale', targetGenerated: true });
    expect(syncModelRoutingFromDesktop().status).toBe('written');
    const mirror = await readFile(h.headless, 'utf8');
    expect(mirror).toContain('off: null');
    expect(mirror).toContain('contextWindow: 256000');
    expect(inspectModelRouting().status).toBe('in-sync');
  });

  it('drops comments instead of copying incidental credentials', async () => {
    const h = await home(DESKTOP_PATCH.replace('provider: aidu', `provider: aidu # ${SECRET}`)
      .replace('        models:', `        # ${SECRET}\n        models:`));
    expect(syncModelRoutingFromDesktop().status).toBe('written');
    expect(await readFile(h.headless, 'utf8')).toBe(GENERATED_PATCH);
  });

  it.each(['home', 'profiles', 'target'] as const)('rejects a redirected %s directory', async (part) => {
    const h = await home(DESKTOP_PATCH);
    const dirs = { home: h.dir, profiles: join(h.dir, 'profiles'), target: join(h.dir, 'profiles', 'headless') };
    const requested = dirs[part];
    const moved = `${requested}-real`;
    if (part === 'home') cleanups.push(() => rm(moved, { recursive: true, force: true }));
    await rename(requested, moved);
    await symlink(moved, requested, process.platform === 'win32' ? 'junction' : 'dir');
    expect(inspectModelRouting()).toMatchObject({ status: 'target-unsafe', targetGenerated: false });
    expect(syncModelRoutingFromDesktop().status).toBe('target-unsafe');
    expect(await readFile(h.headless, 'utf8')).toBe(OLD_PATCH);
  });

  it('rejects a target junction to desktop even when desktop carries a generated marker', async () => {
    const h = await home(OLD_PATCH);
    const targetDir = join(h.dir, 'profiles', 'headless');
    await rm(h.headless);
    await rm(targetDir, { recursive: true });
    await symlink(join(h.dir, 'profiles', 'desktop'), targetDir, process.platform === 'win32' ? 'junction' : 'dir');
    expect(inspectModelRouting()).toMatchObject({ status: 'target-unsafe', sourceValid: true });
    expect(syncModelRoutingFromDesktop().status).toBe('target-unsafe');
    expect(await readFile(h.desktop, 'utf8')).toBe(OLD_PATCH);
  });

  it('rejects a desktop source reached via a symlink or junction', async () => {
    const h = await home(DESKTOP_PATCH);
    const dir = join(h.dir, 'profiles', 'desktop');
    await rename(dir, `${dir}-real`);
    await symlink(`${dir}-real`, dir, process.platform === 'win32' ? 'junction' : 'dir');
    expect(inspectModelRouting().status).toBe('source-invalid');
    expect(syncModelRoutingFromDesktop().status).toBe('source-invalid');
    expect(await readFile(h.headless, 'utf8')).toBe(OLD_PATCH);
  });

  it('rejects a target patch aliased by a hard link', async () => {
    const h = await home(DESKTOP_PATCH);
    await rm(h.headless);
    await link(h.desktop, h.headless);
    expect(inspectModelRouting().status).toBe('target-unsafe');
    expect(syncModelRoutingFromDesktop().status).toBe('target-unsafe');
    expect(await readFile(h.desktop, 'utf8')).toBe(DESKTOP_PATCH);
  });

  it('does not open the old predictable temp path', async () => {
    const h = await home(DESKTOP_PATCH);
    const victim = join(h.dir, 'unrelated.txt');
    await writeFile(victim, 'untouched');
    await link(victim, `${h.headless}.tmp-aiducat`);
    expect(syncModelRoutingFromDesktop().status).toBe('written');
    expect(await readFile(victim, 'utf8')).toBe('untouched');
  });
});