import { mkdir, readFile, realpath, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { describeDshRuntime } from '../../../src/agent/dsh/doctor.js';
import { inspectModelRouting } from '../../../src/agent/dsh/profile-sync.js';
import { readDshProfileModels, resetDshProfileModelsCache } from '../../../src/agent/models.js';

// f0.5++: /doctor must state how DSH was found and where the model routing comes
// from — both have caused real incidents that looked like "the bot is broken".

const cleanups: Array<() => void> = [];
const savedHome = process.env.DSH_HOME;
const savedProfile = process.env.AIDUCAT_DSH_PROFILE;
const savedDshBin = process.env.LARK_CHANNEL_DSH_BIN;
const savedPath = process.env.PATH;

afterEach(() => {
  for (const fn of cleanups.splice(0)) fn();
  if (savedHome === undefined) delete process.env.DSH_HOME;
  else process.env.DSH_HOME = savedHome;
  if (savedProfile === undefined) delete process.env.AIDUCAT_DSH_PROFILE;
  else process.env.AIDUCAT_DSH_PROFILE = savedProfile;
  if (savedDshBin === undefined) delete process.env.LARK_CHANNEL_DSH_BIN;
  else process.env.LARK_CHANNEL_DSH_BIN = savedDshBin;
  if (savedPath === undefined) delete process.env.PATH;
  else process.env.PATH = savedPath;
  resetDshProfileModelsCache();
});

const DESKTOP = [
  '- id: agent-default-model',
  '  name: "@deepseek-ai/dsh-agent-default-model"',
  '  config:',
  '    provider: aidu',
  '    model: Model-X',
  '- id: llm-pi-ai',
  '  name: "@deepseek-ai/dsh-llm-pi-ai"',
  '  config:',
  '    providers:',
  '      aidu:',
  '        models:',
  '          - id: Model-X',
  '          - id: Model-Y',
  '',
].join('\n');

const GENERATED = [
  '# GENERATED by aiduCAT — do not edit by hand.',
  '# Mirrored from the desktop profile so Feishu follows the GUI model settings.',
  '# Source: $DSH_HOME/profiles/desktop/cordis.patch.yml',
  '# Regenerated automatically whenever that file changes.',
  '',
  '',
].join('\n');

async function fixture(opts: { desktop?: string | null; target?: string | null } = {}) {
  const fs = await import('node:fs/promises');
  const home = await fs.mkdtemp(join(await realpath(tmpdir()), 'dsh-doc-'));
  cleanups.push(() => void rm(home, { recursive: true, force: true }));
  await mkdir(join(home, 'profiles', 'desktop'), { recursive: true });
  await mkdir(join(home, 'profiles', 'headless'), { recursive: true });
  if (opts.desktop !== null) {
    await writeFile(join(home, 'profiles', 'desktop', 'cordis.patch.yml'), opts.desktop ?? DESKTOP, 'utf8');
  }
  if (opts.target !== null) {
    await writeFile(join(home, 'profiles', 'headless', 'cordis.patch.yml'), opts.target ?? `${GENERATED}${DESKTOP}`, 'utf8');
  }
  process.env.DSH_HOME = home;
  delete process.env.AIDUCAT_DSH_PROFILE;
  return home;
}

describe('inspectModelRouting', () => {
  it('reports in-sync when the run profile is exactly the mirror', async () => {
    const home = await fixture();
    // Run one sync so the target is the generated mirror.
    const { syncModelRoutingFromDesktop } = await import('../../../src/agent/dsh/profile-sync.js');
    syncModelRoutingFromDesktop();
    const mirror = inspectModelRouting();
    expect(mirror).toMatchObject({
      profile: 'headless',
      sourceValid: true,
      targetGenerated: true,
      inSync: true,
      targetHasExtraEntries: false,
    });
    expect(mirror.source).toContain(join('profiles', 'desktop'));
    expect(mirror.target).toContain(join('profiles', 'headless'));
    expect(await readFile(join(home, 'profiles', 'headless', 'cordis.patch.yml'), 'utf8')).toContain(
      'GENERATED by aiduCAT',
    );
  });

  it('flags a hand-written run profile as out of sync without touching it', async () => {
    // A target that carries an entry the mirror does not manage (ui-settings)
    // is exactly what the doctor warning is for.
    const handwritten = [
      '- id: agent-default-model',
      '  config:',
      '    provider: aidu',
      '    model: Old',
      '- id: ui-settings',
      '  config:',
      '    enabled: false',
      '',
    ].join('\n');
    const home = await fixture({ target: handwritten });
    const before = await readFile(join(home, 'profiles', 'headless', 'cordis.patch.yml'), 'utf8');
    const mirror = inspectModelRouting();
    expect(mirror.inSync).toBe(false);
    expect(mirror.targetGenerated).toBe(false);
    expect(mirror.targetHasExtraEntries).toBe(true);
    // Read-only: /doctor must never rewrite the profile it is inspecting.
    expect(await readFile(join(home, 'profiles', 'headless', 'cordis.patch.yml'), 'utf8')).toBe(before);
  });

  it('reports an invalid source', async () => {
    await fixture({ desktop: '- id: agent-default-model\n  config:\n    provider: aidu\n' });
    expect(inspectModelRouting().sourceValid).toBe(false);
  });
});

describe('describeDshRuntime', () => {
  it('says NOT FOUND and lists the places it looked', async () => {
    await fixture();
    delete process.env.LARK_CHANNEL_DSH_BIN;
    process.env.PATH = join(tmpdir(), 'no-dsh-here');
    const lines = await describeDshRuntime({
      configuredBinary: join(tmpdir(), 'missing-dsh'),
      skipVersion: true,
    });
    // On a machine with the Desktop app installed the probe legitimately finds
    // it; assert the not-found wording only when it truly is absent.
    if (lines[0]?.includes('NOT FOUND')) {
      expect(lines[0]).toContain('PATH');
    } else {
      expect(lines[0]).toContain('dsh binary:');
    }
  });

  it('reports the launch source, version policy, profile and mirror state', async () => {
    await fixture();
    process.env.LARK_CHANNEL_DSH_BIN = process.execPath;
    const { syncModelRoutingFromDesktop } = await import('../../../src/agent/dsh/profile-sync.js');
    syncModelRoutingFromDesktop();
    resetDshProfileModelsCache();
    const lines = await describeDshRuntime({ skipVersion: true });
    const text = lines.join('\n');
    expect(text).toContain('dsh launch:');
    expect(text).toContain('dsh version: not probed');
    expect(text).toContain('dsh profile: headless');
    expect(text).toContain('dsh model: Model-X via provider aidu');
    expect(text).toContain('2 model(s) declared');
    expect(text).toContain('in sync');
    // The parsed profile must agree with what /model lists.
    expect(readDshProfileModels().models).toEqual(['Model-X', 'Model-Y']);
  });

  it('keeps working when DSH_HOME is unset', async () => {
    delete process.env.DSH_HOME;
    const lines = await describeDshRuntime({ skipVersion: true });
    expect(lines.length).toBeGreaterThan(0);
  });
});